/**
 * Regenerates src/html-render-vendor.ts from upstream's packages/shared/src/htmlRender.ts, so
 * pages published by Linguini carry the same theme bootstrap as upstream's and upstream's
 * HtmlRenderFrame card drives them unchanged. Run from prototypes/runtime:
 *   node --import tsx scripts/gen-html-render-vendor.ts
 * html-render.test.ts fails when the vendored copy drifts from upstream.
 */
import { writeFile } from "node:fs/promises";
import * as upstream from "../../../packages/shared/src/htmlRender.ts";
import {
  T3_CODE_DARK_THEME_COLORS,
  T3_CODE_LIGHT_THEME_COLORS,
} from "../../../packages/shared/src/themePalettes.ts";

const probe = '<head><meta charset="utf-8"><meta name="viewport" content="x"></head>';
const injected = upstream.injectHtmlRenderBootstrap(probe);
const styleAndScript = injected.slice(
  "<head>".length,
  injected.length - probe.length + "<head>".length,
);
if (!styleAndScript.startsWith('<style id="t3-theme">') || !styleAndScript.endsWith("</script>"))
  throw new Error("Unexpected upstream bootstrap shape");
const fragment = (appearance: "dark" | "light") =>
  upstream.htmlRenderThemeFragment(
    upstream.htmlRenderTheme(
      appearance === "dark" ? T3_CODE_DARK_THEME_COLORS : T3_CODE_LIGHT_THEME_COLORS,
      appearance,
      upstream.HTML_RENDER_MEASURE_FONTS,
    ),
  );
const values = {
  HTML_RENDER_BOOTSTRAP_STYLE_AND_SCRIPT: styleAndScript,
  HTML_RENDER_MEASURE_FRAGMENT_DARK: fragment("dark"),
  HTML_RENDER_MEASURE_FRAGMENT_LIGHT: fragment("light"),
  HTML_RENDER_THEME_GUIDE: upstream.HTML_RENDER_THEME_GUIDE,
  HTML_RENDER_LAYOUT_GUIDE: upstream.HTML_RENDER_LAYOUT_GUIDE,
  HTML_RENDER_MEASURE_WIDTHS: [...upstream.HTML_RENDER_MEASURE_WIDTHS],
  HTML_RENDER_COLUMN_WIDTH: upstream.HTML_RENDER_COLUMN_WIDTH,
  HTML_RENDER_MIN_HEIGHT: upstream.HTML_RENDER_MIN_HEIGHT,
  HTML_RENDER_MAX_HEIGHT: upstream.HTML_RENDER_MAX_HEIGHT,
  HTML_RENDER_MAX_TITLE_LENGTH: upstream.HTML_RENDER_MAX_TITLE_LENGTH,
};
const body = Object.entries(values)
  .map(
    ([name, value]) =>
      `export const ${name} = ${JSON.stringify(value)}${Array.isArray(value) ? " as const" : ""};`,
  )
  .join("\n");
await writeFile(
  new URL("../src/html-render-vendor.ts", import.meta.url),
  `// Generated by scripts/gen-html-render-vendor.ts from packages/shared/src/htmlRender.ts. Do not edit.\n${body}\n`,
);
